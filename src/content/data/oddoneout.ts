import type { Grade } from '../types'

/**
 * "Which one does not belong?" sets.
 *
 * `others` all share the tag in `attr`; `odd` does not. `why` is the child-facing phrase used in the
 * tier-1 hint ("Hint: most of these are animals.").
 *
 * `level` is the grade the set is written for and `band` is the tier of that grade it belongs to, so
 * a (grade, tier) draws from exactly one bucket: no set is ever reused by another tier or grade, and
 * tier 3 can never serve a set tier 1 could.
 *
 * K is not in this table: kindergarten uses generated colour / shape / count pictures.
 */
export interface OddSet {
  level: Grade
  band: 1 | 2 | 3
  odd: string
  others: string[]
  /** Tag in ODD_TRAITS held by every `other` and not by `odd`. */
  attr: string
  /** Reads as "Hint: most of these ${why}." (keep it under 25 characters). */
  why: string
}

const S = (level: Grade, band: 1 | 2 | 3, odd: string, others: string[], attr: string, why: string): OddSet =>
  ({ level, band, odd, others, attr, why })

